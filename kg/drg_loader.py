# ── DRG 后缀 ──
# 无 CC: 后缀 "5"; 有 CC: 后缀 "9"; 有 MCC: 后缀 "1"
COMPLICATION_SUFFIX: dict[str, str] = {
    "none": "5",
    "CC": "9",
    "MCC": "1",
}


